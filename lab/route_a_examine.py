"""Route A examination helper (ADR-0003 D2, D3) — exploratory, zero result authority (SD10).

For one candidate, fetches the abstract pages of the correcting version and the version before
it (per-version comment, submission history, licence link), downloads both versions' e-print
sources into <out-dir>, records every retrieved byte string's SHA-256, extracts the sources and
prints a unified diff of the .tex files plus any mention of AI assistance. It gathers what the
executor reads; the verdict is the executor's, logged in groundtruth/HARVEST-LOG.md.

Usage:
    python -I -X utf8 lab/route_a_examine.py <arxiv-id> <correcting-version-number> <out-dir>
        [--no-sources]        fetch the abstract pages only
        [--max-diff-lines N]  cap on printed diff lines (default 400)
Standard library only. Pauses 3 s between arXiv requests.
"""

import difflib
import gzip
import hashlib
import html
import io
import re
import sys
import tarfile
import time
import urllib.request
from pathlib import Path

UA = "SYNDEOM-route-a-examine/0.1 (lab; standard library)"
PAUSE = 3.0
AI_WORDS = re.compile(r"ChatGPT|GPT-?\d|Claude|Gemini|DeepSeek|LLM|large language model|"
                      r"language model|AI[- ]assist|AI Math Referee|Copilot|generated by AI|"
                      r"artificial intelligence", re.I)


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=180) as r:
        data = r.read()
        return data, r.headers.get("Content-Type", ""), r.geturl()


def abs_info(arxiv_id, v):
    url = f"https://arxiv.org/abs/{arxiv_id}v{v}"
    data, ctype, final = get(url)
    s = data.decode("utf-8", "replace")
    out = {"url": url, "final_url": final, "bytes": len(data),
           "sha256": hashlib.sha256(data).hexdigest()}
    m = re.search(r'<meta name="citation_title" content="([^"]*)"', s)
    out["title"] = html.unescape(m.group(1)) if m else None
    out["authors"] = [html.unescape(a) for a in re.findall(r'<meta name="citation_author" content="([^"]*)"', s)]
    m = re.search(r'<td class="tablecell comments[^"]*">(.*?)</td>', s, re.S)
    out["comment"] = " ".join(html.unescape(re.sub(r"<[^>]+>", "", m.group(1))).split()) if m else ""
    out["licence_links"] = sorted(set(re.findall(r'href="(https?://[^"]*licenses/[^"]*)"', s)))
    hist = re.search(r'<div class="submission-history">(.*?)</div>', s, re.S)
    out["history"] = " ".join(html.unescape(re.sub(r"<[^>]+>", " ", hist.group(1))).split()) if hist else ""
    m = re.search(r'<meta name="citation_date" content="([^"]*)"', s)
    out["citation_date"] = m.group(1) if m else None
    m = re.search(r'<meta name="citation_online_date" content="([^"]*)"', s)
    out["citation_online_date"] = m.group(1) if m else None
    cats = re.search(r'<td class="tablecell subjects">(.*?)</td>', s, re.S)
    out["subjects"] = " ".join(html.unescape(re.sub(r"<[^>]+>", "", cats.group(1))).split()) if cats else ""
    return out


def fetch_source(arxiv_id, v, out_dir):
    url = f"https://arxiv.org/e-print/{arxiv_id}v{v}"
    data, ctype, final = get(url)
    raw = out_dir / f"eprint-v{v}.bin"
    raw.write_bytes(data)
    info = {"url": url, "final_url": final, "content_type": ctype, "bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(), "file": str(raw)}
    tgt = out_dir / f"v{v}"
    tgt.mkdir(parents=True, exist_ok=True)
    kind = "unknown"
    try:
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:*") as tf:
            try:
                tf.extractall(tgt, filter="data")
            except TypeError:
                tf.extractall(tgt)
        kind = "tar"
    except tarfile.TarError:
        try:
            text = gzip.decompress(data)
            (tgt / "main.tex").write_bytes(text)
            kind = "gzip-single"
        except OSError:
            if data[:5] == b"%PDF-":
                (tgt / "paper.pdf").write_bytes(data)
                kind = "pdf-only"
            else:
                (tgt / "unknown.bin").write_bytes(data)
    info["kind"] = kind
    info["tex_files"] = sorted(str(p.relative_to(tgt)) for p in tgt.rglob("*.tex"))
    return info


def tex_text(root):
    parts = []
    for p in sorted(Path(root).rglob("*.tex")):
        parts.append(f"%%%% FILE {p.relative_to(root)}\n")
        parts.append(p.read_text(encoding="utf-8", errors="replace"))
    return "".join(parts)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    flags = [a for a in sys.argv[1:] if a.startswith("--")]
    if len(args) != 3:
        sys.exit(__doc__)
    arxiv_id, v, out_dir = args[0], int(args[1]), Path(args[2])
    max_lines = 400
    for f in flags:
        if f.startswith("--max-diff-lines="):
            max_lines = int(f.split("=", 1)[1])
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    print(f"== {arxiv_id} correcting version v{v}; access {stamp}")
    # The original is the last version before v that is not a withdrawal (a withdrawn version has
    # no e-print and is a stub); read the submission history of v to find it (Session 13 finding).
    head = abs_info(arxiv_id, v)
    withdrawn = {int(n) for n in re.findall(r"\[v(\d+)\][^\[]*\(withdrawn\)", head["history"])}
    orig = v - 1
    while orig > 1 and orig in withdrawn:
        orig -= 1
    if withdrawn:
        print(f"-- withdrawn versions per the submission history: {sorted(withdrawn)}; "
              f"original taken as v{orig}")
    time.sleep(PAUSE)
    for ver in (orig, v):
        info = abs_info(arxiv_id, ver)
        print(f"-- abs v{ver}: {info['url']} ({info['bytes']} bytes, sha256 {info['sha256']})")
        print(f"   title: {info['title']}")
        print(f"   authors: {'; '.join(info['authors'])}")
        print(f"   subjects: {info['subjects']}")
        print(f"   comment: {info['comment']}")
        print(f"   licence links: {info['licence_links']}")
        print(f"   history: {info['history']}")
        time.sleep(PAUSE)
    if "--no-sources" in flags:
        return
    srcs = {}
    for ver in (orig, v):
        srcs[ver] = fetch_source(arxiv_id, ver, out_dir)
        s = srcs[ver]
        print(f"-- e-print v{ver}: {s['url']} -> {s['content_type']} {s['bytes']} bytes sha256 {s['sha256']} kind={s['kind']} tex={s['tex_files']}")
        time.sleep(PAUSE)
    old = tex_text(out_dir / f"v{orig}").splitlines()
    new = tex_text(out_dir / f"v{v}").splitlines()
    diff = list(difflib.unified_diff(old, new, f"v{orig}", f"v{v}", n=2, lineterm=""))
    print(f"-- tex diff v{orig} -> v{v}: {len(diff)} lines (showing up to {max_lines})")
    for line in diff[:max_lines]:
        print(line)
    if len(diff) > max_lines:
        print(f"... {len(diff) - max_lines} more diff lines in {out_dir}")
    (out_dir / "tex.diff").write_text("\n".join(diff) + "\n", encoding="utf-8")
    hits = sorted(set(m.group(0) for m in AI_WORDS.finditer("\n".join(new))))
    print(f"-- AI-assistance mentions in v{v} sources: {hits if hits else 'none'}")


if __name__ == "__main__":
    main()
